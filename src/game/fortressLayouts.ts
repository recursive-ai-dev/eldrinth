/**
 * Every shard lives in an authored, self-contained fortress. A layout has
 * a one-tile door at its north edge and seventeen enclosed interior rows.
 */
function fortress(doorColumn: number, interior: string[]) {
  if (interior.length !== 17 || interior.some((row) => row.length !== 24)) {
    throw new Error("Fortress layouts must be 26 by 19 tiles.");
  }
  return [
    `${"#".repeat(doorColumn)}D${"#".repeat(25 - doorColumn)}`,
    ...interior.map((row) => `#${row}#`),
    "##########################",
  ];
}

